/**
 * Get providers grouped by category
 */
export function getProvidersByCategory(): Record<APIProviderCategory, APIProvider[]> {
    const grouped = {} as Record<APIProviderCategory, APIProvider[]>;
    for (const cat of Object.keys(PROVIDER_CATEGORIES) as APIProviderCategory[]) {
        grouped[cat] = API_PROVIDERS.filter(p => p.category === cat);
    }
    return grouped;
}

/**
 * Get a single provider by ID
 */
export function getProvider(id: string): APIProvider | undefined {
    return API_PROVIDERS.find(p => p.id === id);
}
